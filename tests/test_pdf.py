"""The PDF twin of the .docx."""

from __future__ import annotations

from pathlib import Path

from sarai.docgen.pdf import render_pdf, to_html
from sarai.models import ActionItem, MeetingType, MinutesJSON


def _minutes(**extra: object) -> MinutesJSON:
    return MinutesJSON.model_validate(
        {
            "title": "ประชุมทีม",
            "meeting_date": "2026-11-18 14:30",
            "summary": "สรุปการประชุม",
            "action_items": [
                ActionItem(task="ส่งเอกสาร", owner="คุณมาลี", source_quote="จะส่งให้").model_dump()
            ],
            **extra,
        }
    )


def test_model_output_is_escaped() -> None:
    html = to_html(
        _minutes(summary="<script>alert(1)</script>"), model="m", meeting_type=MeetingType.GENERAL
    )
    assert "<script>" not in html
    assert "&lt;script&gt;" in html


def test_headings_follow_the_meeting_type() -> None:
    html = to_html(_minutes(), model="m", meeting_type=MeetingType.LECTURE)
    assert "สาระสำคัญ" in html


def test_render_writes_a_pdf(tmp_path: Path) -> None:
    dest = render_pdf(_minutes(), tmp_path / "out.pdf", model="m")
    assert dest.read_bytes()[:5] == b"%PDF-"


def test_tables_have_fixed_columns_and_wrappable_thai() -> None:
    """A long unspaced Thai quote must not widen the action table off the page."""
    quote = "เดี๋ยวลองเอาอันนี้ไปลองใช้กับอายุโคกคิวบดูครับผมคิดว่ามันน่าจะแม่นขึ้น"
    minutes = _minutes(
        action_items=[ActionItem(task="ส่งเอกสาร", owner="คุณมาลี", source_quote=quote).model_dump()]
    )
    html = to_html(minutes, model="m", meeting_type=MeetingType.GENERAL)
    assert "table-layout: fixed" in html
    assert "<col style='width:62%'>" in html
    assert quote not in html  # broken up by zero-width spaces
    assert quote in html.replace("​", "")


def test_attendee_table_has_a_name_and_role_header() -> None:
    html = to_html(
        _minutes(attendees=[{"name": "คุณสมชาย", "role": "Product lead"}]),
        model="m",
        meeting_type=MeetingType.GENERAL,
    )
    assert "<th>ชื่อ</th><th>ตำแหน่ง</th>" in html


def test_english_part_follows_the_thai_part() -> None:
    html = to_html(
        _minutes(english={"title": "Team meeting", "summary": "English summary"}),
        model="m",
        meeting_type=MeetingType.GENERAL,
    )
    assert html.index("สรุปการประชุม") < html.index("Team meeting")
    assert html.index("Team meeting") < html.index("English summary")
    assert "ฉบับภาษาไทย" not in html and "English version" not in html


def test_each_part_warns_that_ai_wrote_it() -> None:
    html = to_html(
        _minutes(english={"title": "Team meeting"}), model="m", meeting_type=MeetingType.GENERAL
    )
    assert html.index("สรุปนี้จัดทำโดย AI และอาจมีข้อผิดพลาด โปรดตรวจสอบความถูกต้องก่อนนำไปใช้") < html.index(
        "This summary was generated by AI and may contain mistakes. Please verify it before use."
    )


def test_discussion_does_not_list_speakers() -> None:
    html = to_html(
        _minutes(discussion=[{"topic": "หัวข้อ", "points": ["ข้อ"], "speakers": ["คุณสมชาย"]}]),
        model="m",
        meeting_type=MeetingType.GENERAL,
    )
    assert "คุณสมชาย" not in html


def test_no_english_part_without_a_translation() -> None:
    html = to_html(_minutes(), model="m", meeting_type=MeetingType.GENERAL)
    assert "<section class='part' lang='en'>" not in html
